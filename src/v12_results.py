"""Collect v12 reports with the unchanged official metric definitions.

Composite-loss and deterministic-validation-SSD checkpoints are reported in
separate roots.  The official combined metrics are evaluated on concatenated
predictions: averaging the two per-noise summaries would change official PRD.
"""

import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import yaml

from mecge_table1_collect_official_protocol import (
    BIN_EDGES,
    load_result,
    metric_fields,
    metric_values,
    parse_name,
    write_csv,
)
from mecge_table1_collect_results import collect_robustness, collect_table1, write_rows
from mecge_table1_robustness_bins import label


APP = Path(__file__).resolve().parent


def run_report(script, *arguments):
    subprocess.run(
        [sys.executable, "-B", str(APP / script), *map(str, arguments)],
        cwd=APP,
        check=True,
    )


def result_files(report_root):
    results = []
    for path in sorted((report_root / "official_results").glob("*.pkl")):
        parsed = parse_name(path)
        if parsed and parsed["noise_version"] in ("nv1", "nv2"):
            results.append((path, parsed))
    return results


def collect_combined_without_amplitudes(results, output_dir):
    """Keep the official table/schema when amplitude bins cannot be computed."""
    grouped = {}
    for path, parsed in results:
        key = (parsed["model"], parsed["seed"])
        grouped.setdefault(key, {})[parsed["noise_version"]] = path
    rows = []
    for (model, seed), by_nv in sorted(grouped.items()):
        if not all(noise in by_nv for noise in ("nv1", "nv2")):
            print(f"Skipping combined nv1+nv2 row for {model}/{seed}: both result PKLs are required.", flush=True)
            continue
        loaded = [load_result(by_nv[noise]) for noise in ("nv1", "nv2")]
        clean = np.concatenate([pair[0] for pair in loaded], axis=0)
        prediction = np.concatenate([pair[1] for pair in loaded], axis=0)
        row = {
            "experiment": "table1_official_nv1_nv2",
            "model": model,
            "dataset_protocol": "qtdb_train_qtdb_test",
            "noise_version": "nv1_nv2",
            "seed": seed,
            "alpha": "",
            "result_name": f"{model}__qtdb_train_qtdb_test__nv1_nv2__{seed}",
        }
        metric_fields(row, metric_values(clean, prediction))
        rows.append(row)
    write_csv(output_dir / "table1_comparison__official_nv1_nv2.csv", rows)


def report_files(report_root):
    """Find report artifacts at this selector's depth, excluding the other one."""
    patterns = (
        "analysis/*.csv",
        "*/results/**/metrics_*.csv",
        "*/results/**/metrics_qtdb_pkl_test.yaml",
        "*/controlled_tests/*/metrics_summary.csv",
        "*/controlled_tests/robustness_bins_summary.csv",
    )
    return {path for pattern in patterns for path in report_root.glob(pattern)}


def write_report_manifest(report_root, checkpoint_label, results, robust_versions, regenerated):
    retained = report_files(report_root) - regenerated
    if retained:
        print(
            f"WARNING: {checkpoint_label}: {len(retained)} existing report files were retained "
            "and NOT regenerated. They may be stale; see analysis/report_manifest.json.",
            flush=True,
        )
    manifest = {
        "checkpoint_selector": checkpoint_label,
        "active_result_names": sorted(path.stem for path, _ in results),
        "robustness_noise_versions": sorted(robust_versions),
        "regenerated": sorted(str(path.relative_to(report_root)) for path in regenerated),
        "retained_not_regenerated": sorted(str(path.relative_to(report_root)) for path in retained),
        "note": "Retained files are historical artifacts, not reports regenerated by this collection.",
    }
    target = report_root / "analysis" / "report_manifest.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    temporary.replace(target)


def collect_selector(root, report_root, checkpoint_label, results, amplitude_files):
    print(f"Collecting {checkpoint_label} reports under {report_root / 'analysis'}", flush=True)
    versions = set()
    regenerated, metric_paths, robustness_paths = set(), set(), set()
    active_names = {path.stem for path, _ in results}
    active_runs = {(parsed["model"], parsed["seed"], parsed["noise_version"]) for _, parsed in results}
    for path, parsed in results:
        model, noise, seed = parsed["model"], parsed["noise_version"], parsed["seed"]
        versions.add(noise)
        # Both checkpoint selectors use the one configuration from the training job.
        config_path = root / model.removeprefix("lstm_") / noise / seed / "resolved_config.yaml"
        model_name = model
        if config_path.is_file():
            with config_path.open(encoding="utf-8") as handle:
                model_name = (yaml.safe_load(handle) or {}).get("model_name", model)
        eval_dir = report_root / model / "results" / path.stem / model_name / checkpoint_label
        run_report("mecge_table1_official_result_metrics.py", "--result-pkl", path, "--output-dir", eval_dir)
        regenerated.update(eval_dir / name for name in (
            "metrics_qtdb_pkl_test.yaml", "metrics_per_window.csv", "metrics_summary.csv",
        ))
        metric_paths.add(eval_dir / "metrics_qtdb_pkl_test.yaml")
        amplitude = amplitude_files.get(int(noise[2:]))
        if amplitude is not None:
            run_report(
                "mecge_table1_robustness_bins.py",
                "--metrics-per-window", eval_dir / "metrics_per_window.csv",
                "--rnd-test", amplitude, "--output-root", report_root / model / "controlled_tests",
                "--result-model", model, "--noise-version", noise, "--seed", seed.removeprefix("seed"),
            )
            controlled = report_root / model / "controlled_tests"
            for low, high in zip(BIN_EDGES[:-1], BIN_EDGES[1:]):
                name = f"{model}__qtdb_robustness_alpha_{label(low)}_{label(high)}__{noise}__{seed}"
                robustness_paths.add(controlled / name / "metrics_summary.csv")
            regenerated.add(controlled / "robustness_bins_summary.csv")
        else:
            print(f"Skipping robustness bins for {checkpoint_label}/{path.stem}: no amplitude array supplied/found.", flush=True)

    regenerated.update(robustness_paths)
    robust_versions = {noise for noise in versions if amplitude_files.get(int(noise[2:])) is not None}
    # The unchanged collector's glob also finds reports whose source PKL was
    # removed. Restrict aggregation to current inputs and regenerated metrics.
    # Refresh an old per-nv table to empty when that nv no longer has results.
    table_versions = versions | {
        noise for noise in ("nv1", "nv2")
        if (report_root / "analysis" / f"table1_comparison__qtdb_train_qtdb_test__{noise}.csv").is_file()
    }
    for noise in [*sorted(table_versions), "all"]:
        table = report_root / "analysis" / f"table1_comparison__qtdb_train_qtdb_test__{noise}.csv"
        rows = [row for row in collect_table1(report_root, noise)
                if row["result_name"] in active_names and Path(row["metrics_file"]) in metric_paths]
        write_rows(table, rows)
        regenerated.add(table)
        if noise in robust_versions or (noise == "all" and robust_versions):
            table = report_root / "analysis" / f"robustness_comparison__qtdb__{noise}.csv"
            rows = [row for row in collect_robustness(report_root, noise)
                    if row["noise_version"] in robust_versions
                    and (row["model"], row["seed"], row["noise_version"]) in active_runs
                    and Path(row["metrics_file"]) in robustness_paths]
            write_rows(table, rows)
            regenerated.add(table)
    if all(amplitude_files.get(nv) is not None for nv in (1, 2)):
        run_report(
            "mecge_table1_collect_official_protocol.py",
            "--official-results-dir", report_root / "official_results",
            "--rnd-test-nv1", amplitude_files[1], "--rnd-test-nv2", amplitude_files[2],
            "--output-dir", report_root / "analysis",
        )
        regenerated.add(report_root / "analysis" / "robustness_comparison__official_nv1_nv2.csv")
    else:
        collect_combined_without_amplitudes(results, report_root / "analysis")
        print(
            f"Skipping combined robustness bins for {checkpoint_label}: amplitude arrays for both noise versions are required. "
            "The combined official metric table is still generated for complete nv1+nv2 pairs.",
            flush=True,
        )
    regenerated.add(report_root / "analysis" / "table1_comparison__official_nv1_nv2.csv")
    write_report_manifest(report_root, checkpoint_label, results, robust_versions, regenerated)


def collect_results(root, amplitude_files=None):
    root = Path(root).resolve()
    amplitude_files = amplitude_files or {}
    selectors = [
        (root, "best_loss", result_files(root)),
        (root / "validation_ssd", "best_val_ssd", result_files(root / "validation_ssd")),
    ]
    if not any(results for _, _, results in selectors):
        raise FileNotFoundError(
            f"No nv1/nv2 result PKLs found under {root / 'official_results'} "
            f"or {root / 'validation_ssd' / 'official_results'}"
        )
    for report_root, checkpoint_label, results in selectors:
        if not results:
            print(f"Skipping {checkpoint_label} reports: no result PKLs found under {report_root / 'official_results'}.", flush=True)
            if (report_root / "analysis").is_dir():
                write_report_manifest(report_root, checkpoint_label, results, set(), set())
            continue
        collect_selector(root, report_root, checkpoint_label, results, amplitude_files)
